        var legacyAccount = normalizedAccounts.FirstOrDefault(account => account.AccountKey == "default")
            ?? defaultAccount
            ?? normalizedAccounts.FirstOrDefault();
        await WriteAtomicallyAsync(
            callerIdPath,
            legacyAccount is null ? string.Empty : legacyAccount.OutboundCallerId + "\n" + legacyAccount.Domain + "\n",
            ct);

        var outboundEndpoint = defaultAccount is null
            ? null
            : defaultAccount.AccountKey == "default"
                ? Orbita.Contracts.CrmTelephonyProviders.Plusofon
                : $"plusofon-{GetEndpointKey(officeId, defaultAccount.AccountKey)}";
        await WriteOutboundSelectionAsync(
            officeId,
            Orbita.Contracts.CrmTelephonyProviders.Plusofon,
            outboundEndpoint,
            ct);
        return (true, null);
    }

